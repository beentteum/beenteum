
-- BEENTEUM 초기 데이터베이스 스키마
-- Flyway Migration: V1__init_schema.sql
-- PostgreSQL 18 / PostGIS

-- 1. PostGIS 확장
CREATE EXTENSION IF NOT EXISTS postgis;

-- 2. 회원
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('USER', 'ADMIN'))
);

-- 3. 카페
CREATE TABLE cafes (
    cafe_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_place_id VARCHAR(100),
    name VARCHAR(200) NOT NULL,
    address TEXT,
    road_address TEXT,
    location GEOMETRY(POINT, 4326),
    admin_dong_code VARCHAR(30),
    commercial_area_code VARCHAR(30),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT chk_cafes_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_cafes_location
    ON cafes USING GIST (location);

CREATE INDEX idx_cafes_commercial_area
    ON cafes (commercial_area_code);

CREATE UNIQUE INDEX uq_cafes_external_place_id
    ON cafes (external_place_id)
    WHERE external_place_id IS NOT NULL;

-- 4. 카페 공간 정보
CREATE TABLE cafe_space_info (
    cafe_id BIGINT PRIMARY KEY
        REFERENCES cafes(cafe_id),
    business_hours JSONB,
    seat_type VARCHAR(100),
    seat_count INTEGER,
    outlet_available BOOLEAN,
    wifi_available BOOLEAN,
    noise_level VARCHAR(30),
    updated_by BIGINT REFERENCES users(user_id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_cafe_seat_count
        CHECK (seat_count IS NULL OR seat_count >= 0)
);

-- 5. QR 코드
CREATE TABLE qr_codes (
    qr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cafe_id BIGINT NOT NULL REFERENCES cafes(cafe_id),
    qr_token VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_qr_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'REVOKED'))
);

CREATE INDEX idx_qr_codes_cafe
    ON qr_codes (cafe_id);

-- 6. 현장 인증 세션
CREATE TABLE field_auth_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    cafe_id BIGINT NOT NULL REFERENCES cafes(cafe_id),
    qr_verified BOOLEAN NOT NULL DEFAULT FALSE,
    location_verified BOOLEAN NOT NULL DEFAULT FALSE,
    authenticated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT chk_auth_session_status
        CHECK (status IN ('ACTIVE', 'EXPIRED', 'REVOKED'))
);

CREATE INDEX idx_auth_sessions_user_cafe
    ON field_auth_sessions (user_id, cafe_id, authenticated_at DESC);

-- 7. 혼잡도 제보
CREATE TABLE reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE
        REFERENCES field_auth_sessions(session_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    cafe_id BIGINT NOT NULL REFERENCES cafes(cafe_id),
    congestion VARCHAR(20) NOT NULL,
    seat_availability VARCHAR(30),
    noise_level VARCHAR(30),
    party_size VARCHAR(10),
    status VARCHAR(20) NOT NULL DEFAULT 'VALID',
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_reports_congestion
        CHECK (congestion IN ('LOW', 'NORMAL', 'HIGH')),

    CONSTRAINT chk_reports_status
        CHECK (status IN ('VALID', 'PENDING', 'EXCLUDED')),

    CONSTRAINT chk_reports_party_size
        CHECK (party_size IS NULL OR party_size IN ('1', '2', '3', '4+'))
);

CREATE INDEX idx_reports_cafe_time
    ON reports (cafe_id, reported_at DESC);

CREATE INDEX idx_reports_aggregate
    ON reports (cafe_id, reported_at DESC)
    WHERE status = 'VALID';

-- 8. 예상 혼잡도 집계
CREATE TABLE congestion_aggregates (
    cafe_id BIGINT NOT NULL REFERENCES cafes(cafe_id),
    day_of_week SMALLINT NOT NULL,
    hour_slot SMALLINT NOT NULL,
    sample_count INTEGER NOT NULL DEFAULT 0,
    congestion VARCHAR(20),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (cafe_id, day_of_week, hour_slot),

    CONSTRAINT chk_aggregate_day
        CHECK (day_of_week BETWEEN 1 AND 7),

    CONSTRAINT chk_aggregate_hour
        CHECK (hour_slot BETWEEN 0 AND 23),

    CONSTRAINT chk_aggregate_sample
        CHECK (sample_count >= 0),

    CONSTRAINT chk_aggregate_congestion
        CHECK (congestion IS NULL OR congestion IN ('LOW', 'NORMAL', 'HIGH'))
);

-- 9. 즐겨찾기
CREATE TABLE favorites (
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    cafe_id BIGINT NOT NULL REFERENCES cafes(cafe_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, cafe_id)
);

CREATE INDEX idx_favorites_cafe
    ON favorites (cafe_id);

-- 10. 관리자 감사 로그
CREATE TABLE admin_audit_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES users(user_id),
    target_type VARCHAR(50) NOT NULL,
    target_id BIGINT NOT NULL,
    action VARCHAR(100) NOT NULL,
    before_value JSONB,
    after_value JSONB,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_admin_audit_target
    ON admin_audit_logs (target_type, target_id);

-- 11. 공공데이터 스냅샷
CREATE TABLE public_data_snapshots (
    public_data_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR(200) NOT NULL,
    data_type VARCHAR(50) NOT NULL,
    spatial_key_type VARCHAR(30) NOT NULL,
    spatial_key VARCHAR(200) NOT NULL,
    day_of_week SMALLINT,
    time_slot SMALLINT,
    reference_date DATE NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_cycle VARCHAR(50),
    payload JSONB NOT NULL,

    CONSTRAINT chk_public_data_day
        CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),

    CONSTRAINT chk_public_data_hour
        CHECK (time_slot IS NULL OR time_slot BETWEEN 0 AND 23),

    CONSTRAINT chk_public_spatial_key_type
        CHECK (spatial_key_type IN (
            'COORD', 'ADMIN_DONG', 'COMMERCIAL_AREA', 'GRID'
        ))
);

CREATE INDEX idx_public_data_lookup
    ON public_data_snapshots (
        data_type,
        spatial_key_type,
        spatial_key,
        reference_date DESC
    );
